#!/usr/bin/env python3
"""Generate the readable views in catalogue/ from data/.

Outputs (never edit by hand):
  catalogue/CATALOGUE.md      full catalogue: summary table, by subject, record details
  catalogue/SHORTLISTS.md     rule-based shortlists
  catalogue/LEARNING_PATH.md  suggested sequence from data/learning_path.json
  catalogue/trainings.csv     flat export for spreadsheets
"""

from __future__ import annotations

import csv
import io
import sys

from common import (
    CATALOGUE_DIR, CATEGORY_LABELS, DB_PATH, FREE_MODELS, MISSING, PATH_PATH, load_json,
)

HEADER = "<!-- GENERATED by scripts/build_catalogue.py from data/. Do not edit by hand. -->\n\n"

EXEC_CATS = {"strategy-operating-models", "governance-regulation-risk", "security", "sales-marketing-partnerships"}
TECH_CATS = {"python-data", "machine-learning-deep-learning", "rag-evals-llmops", "cloud-platforms", "generative-ai-agents"}


# ---------- formatting helpers ----------

def md(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def is_free(rec) -> bool:
    return rec["pricing"]["model"] in FREE_MODELS


def money(amount, currency) -> str:
    if amount in MISSING:
        return amount
    if amount == int(amount):
        return f"{currency} {int(amount):,}"
    return f"{currency} {amount:,.2f}"


def price_text(rec) -> str:
    p = rec["pricing"]
    if p["model"] == "free":
        return "Free"
    eur = p["eur_approx"]
    if eur in MISSING:
        return f"{md(p['advertised'])} (EUR {eur})"
    if eur == 0:
        return f"Free ({md(p['advertised'])})"
    if p["currency"] == "EUR":
        return md(p["advertised"])
    return f"≈ EUR {eur:,.0f} ({md(p['advertised'])})"


def hours_text(rec) -> str:
    h = rec["delivery"]["study_hours"]
    lo, hi = h["min"], h["max"]
    if lo in MISSING and hi in MISSING:
        return lo if lo == hi else "not published"
    if lo in MISSING:
        return f"up to {hi:g} h"
    if hi in MISSING or lo == hi:
        return f"{lo:g} h"
    return f"{lo:g}–{hi:g} h"


def rating_text(rec) -> str:
    r = rec["learner_rating"]
    if r["status"] != "published":
        return f"Unrated ({r['status']})"
    return f"{r['value']:g}/{r['scale']:g} from {r['review_count']:,} {r['count_type']} ({md(r['platform'])})"


def class_label(rec) -> str:
    return {
        "highly-rated": "Highly rated",
        "rated-small-sample": "Rated (small sample)",
        "rated-below-threshold": "Rated (below 4.5/5)",
        "credible-but-unrated": "Credible but unrated",
    }[rec["rating_class"]]


def cred_label(rec) -> str:
    return rec["credential"]["type"].replace("-", " ")


def cats_text(rec) -> str:
    return ", ".join(CATEGORY_LABELS[c] for c in rec["categories"])


def link(rec) -> str:
    return f"[{md(rec['title'])}]({rec['official_url']})"


def anchor(rec) -> str:
    return f"[`{rec['id']}`](CATALOGUE.md#{rec['id']})"


def bullet_list(items, empty="None stated") -> str:
    if not items:
        return f"- {empty}\n"
    return "".join(f"- {md(i)}\n" for i in items)


def by_score(records):
    return sorted(records, key=lambda r: (-r["suitability"]["score"], r["id"]))


# ---------- views ----------

def catalogue_md(db) -> str:
    active = [r for r in db["records"] if r["status"] != "archived"]
    archived = [r for r in db["records"] if r["status"] == "archived"]
    out = io.StringIO()
    out.write(HEADER)
    out.write("# AI training catalogue\n\n")
    out.write(
        f"Database updated {db['updated_on']}. {len(active)} current offerings"
        f" ({sum(is_free(r) for r in active)} free or free-to-audit, {sum(not is_free(r) for r in active)} paid)"
        f", {len(archived)} archived.\n\n"
        f"EUR amounts are approximate, converted from the advertised currency using {db['fx']['source']} rates"
        f" dated {db['fx']['rate_date']} ({db['fx']['source_url']}). They exclude VAT and extra costs unless stated.\n\n"
        "**Suitability** (0–100) is the maintainer's assessment against the objectives in "
        "[docs/SCORING.md](../docs/SCORING.md). It is separate from learner ratings, and ratings from different "
        "platforms are not directly comparable.\n\n"
    )

    out.write("## Summary (sorted by suitability)\n\n")
    out.write("| Suitability | Offering | Provider | Free/paid | Level | Study hours | Credential | Cost | Learner rating |\n")
    out.write("|---:|---|---|---|---|---|---|---|---|\n")
    for r in by_score(active):
        out.write(
            f"| {r['suitability']['score']} ({r['suitability']['confidence']}) | {link(r)}<br>[`{r['id']}`](#{r['id']}) "
            f"| {md(r['provider'])} | {'Free' if is_free(r) else 'Paid'} | {r['level']} | {hours_text(r)} "
            f"| {cred_label(r)} | {price_text(r)} | {class_label(r)}: {rating_text(r)} |\n"
        )

    out.write("\n## By subject\n\n")
    for cat, label in CATEGORY_LABELS.items():
        recs = by_score([r for r in active if cat in r["categories"]])
        out.write(f"### {label}\n\n")
        if not recs:
            out.write("_No current offerings._\n\n")
            continue
        for r in recs:
            out.write(
                f"- **{r['suitability']['score']}** [`{r['id']}`](#{r['id']}) {link(r)}, {md(r['provider'])}: "
                f"{'free' if is_free(r) else 'paid'}, {r['level']}, {hours_text(r)}, {cred_label(r)}\n"
            )
        out.write("\n")

    out.write("## Record details\n\n")
    for r in sorted(active, key=lambda r: r["id"]):
        out.write(record_detail(r))

    if archived:
        out.write("## Archived offerings\n\n")
        out.write("| ID | Offering | Archived | Reason | Superseded by |\n|---|---|---|---|---|\n")
        for r in sorted(archived, key=lambda r: r["id"]):
            a = r["archive"]
            out.write(f"| `{r['id']}` | {link(r)} | {a['date']} | {md(a['reason'])} | {a.get('superseded_by', '')} |\n")
        out.write("\n")
    return out.getvalue()


def record_detail(r) -> str:
    p, d, c, s, a = r["pricing"], r["delivery"], r["credential"], r["suitability"], r["ireland_access"]
    rt = r["learner_rating"]
    lines = [
        f'<a id="{r["id"]}"></a>\n',
        f"### {md(r['title'])}\n",
        f"`{r['id']}` · {md(r['provider'])} on {md(r['platform'])} · [official page]({r['official_url']}) · status: {r['status']}\n",
        f"**Subjects:** {cats_text(r)}  ",
        f"**Type:** {r['offering_type']} · **Level:** {r['level']} · **Audience:** {md(r['audience'])}\n",
        "**Prerequisites**\n",
        bullet_list(r["prerequisites"], "None stated by the provider"),
        "**Learning outcomes**\n",
        bullet_list(r["learning_outcomes"]),
        "**Practical work**\n",
        bullet_list(r["practical_work"], "None advertised"),
        f"**Assessment:** {r['assessment']['type']}: {md(r['assessment']['description'])}  ",
        f"**Credential:** {cred_label(r)}, issued by {md(c['issuer'])}. Academic credit: {md(c['academic_credit'])}. Renewal: {md(c['renewal'])}\n",
        f"**Delivery:** {d['format']}; {md(d['duration'])}; study hours {hours_text(r)} ({md(d['study_hours']['basis'])}); "
        f"access: {md(d['access_period'])}; starts: {md(d['start_dates'])}  ",
        f"**From Ireland:** {a['status']}. {md(a['notes'])} Live-session time zone: {md(a['live_session_timezone'])}\n",
        f"**Price:** {p['model']}; advertised {md(p['advertised'])}; approx. {money(p['eur_approx'], 'EUR')}\n",
    ]
    lines.append("**Additional costs**\n")
    lines.append(bullet_list(p["additional_costs"], "None identified"))
    lines.append("**Financial aid / discounts (verified)**\n")
    lines.append(bullet_list(p["financial_aid"], "None verified"))
    if rt["status"] == "published":
        lines.append(
            f"**Learner rating:** {class_label(r)}. {rating_text(r)}; scope: {md(rt['scope'])}; "
            f"[source]({rt['source_url']}), verified {rt['verified_on']}\n"
        )
    else:
        lines.append(f"**Learner rating:** {class_label(r)} (rating {rt['status']})\n")
    lines += [
        "**Quality evidence**\n", bullet_list(r["quality_evidence"]),
        "**Limitations**\n", bullet_list(r["limitations"]),
        f"**Relevance:** {md(r['relevance'])}\n",
        f"**Suitability {s['score']}/100** (confidence {s['confidence']}). Components: "
        + ", ".join(f"{k} {v}" for k, v in s["components"].items())
        + f". {md(s['rationale'])}\n",
        f"**Verification:** {r['verification']['last_verified']} via {r['verification']['method']}.",
    ]
    if r["verification"]["gaps"]:
        lines.append(" Gaps: " + "; ".join(md(g) for g in r["verification"]["gaps"]) + ".")
    if r["verification"]["conflicts"]:
        lines.append(" Conflicts: " + "; ".join(md(g) for g in r["verification"]["conflicts"]) + ".")
    lines.append("\n")
    lines.append("**Sources**\n")
    lines.append("".join(f"- <{src['url']}>: {md(src['supports'])} (accessed {src['accessed']})\n" for src in r["sources"]))
    u = r["user"]
    lines.append(f"**My status:** {u['completion_status']}" + (f". Notes: {md(u['notes'])}" if u["notes"] else "") + "\n")
    lines.append("\n---\n\n")
    text = "\n".join(lines)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text


def shortlist_rows(recs, out):
    out.write("| # | Suitability | Offering | Provider | Level | Hours | Cost | Credential | Rating |\n")
    out.write("|---:|---:|---|---|---|---|---|---|---|\n")
    for i, r in enumerate(recs, 1):
        out.write(
            f"| {i} | {r['suitability']['score']} | {link(r)}<br>{anchor(r)} | {md(r['provider'])} | {r['level']} "
            f"| {hours_text(r)} | {price_text(r)} | {cred_label(r)} | {class_label(r)} |\n"
        )
    out.write("\n")


def shortlists_md(db) -> str:
    active = [r for r in db["records"] if r["status"] in ("active", "upcoming")]
    out = io.StringIO()
    out.write(HEADER)
    out.write("# Shortlists\n\n")
    out.write(
        f"Generated from the database dated {db['updated_on']}. Each list uses a fixed, published rule so it can be "
        "regenerated after every refresh. Suitability scoring is explained in [docs/SCORING.md](../docs/SCORING.md).\n\n"
    )

    free = by_score([r for r in active if is_free(r)])[:10]
    out.write("## Best free training\n\n")
    out.write("Rule: pricing model is free, free audit or publicly funded; top 10 by suitability. "
              "Free audit usually excludes graded work and the certificate.\n\n")
    shortlist_rows(free, out)

    paid = [r for r in active if not is_free(r) and r["suitability"]["score"] >= 70]
    paid = sorted(paid, key=lambda r: (-(r["suitability"]["score"] + r["suitability"]["components"]["value"]) / 2, r["id"]))[:10]
    out.write("## Best-value paid training\n\n")
    out.write("Rule: paid offerings with suitability ≥ 70, ranked by the mean of suitability and the value-for-money "
              "component; top 10.\n\n")
    shortlist_rows(paid, out)

    exe = by_score([r for r in active if EXEC_CATS & set(r["categories"])])[:12]
    out.write("## Executive, strategy and governance\n\n")
    out.write("Rule: tagged strategy, governance, security or sales/marketing; top 12 by suitability.\n\n")
    shortlist_rows(exe, out)

    tech = by_score([
        r for r in active
        if TECH_CATS & set(r["categories"]) and r["suitability"]["components"]["practical"] >= 70
    ])[:12]
    out.write("## Practical technical training\n\n")
    out.write("Rule: tagged generative AI, Python/data, ML/DL, RAG/LLMOps or cloud, with a practical-work component "
              "≥ 70; top 12 by suitability.\n\n")
    shortlist_rows(tech, out)
    return out.getvalue()


def learning_path_md(db, path) -> str:
    recs = {r["id"]: r for r in db["records"]}
    out = io.StringIO()
    out.write(HEADER)
    out.write(f"# {path['title']}\n\n{path['intro']}\n\n")
    out.write(
        f"Hours and costs come from the database dated {db['updated_on']}; EUR conversions use {db['fx']['source']} "
        f"rates dated {db['fx']['rate_date']}. Totals add only published figures. Anything not published or not verified "
        "is listed separately, so the totals are a floor, not a quote.\n\n"
    )
    grand = {"core": [0.0, 0.0, 0.0], "optional": [0.0, 0.0, 0.0]}
    unknown = []
    for n, stage in enumerate(path["stages"], 1):
        out.write(f"## Stage {n}: {stage['name']}\n\n{stage['goal']}\n\n")
        out.write("| Step | Offering | Prerequisites | Hours | Cost | Credential | Why |\n|---|---|---|---|---|---|---|\n")
        for i, step in enumerate(stage["steps"], 1):
            r = recs[step["id"]]
            kind = "optional" if step.get("optional") else "core"
            h = r["delivery"]["study_hours"]
            eur = r["pricing"]["eur_approx"]
            if h["min"] in MISSING or h["max"] in MISSING:
                unknown.append(f"`{r['id']}`: study hours {h['min'] if h['min'] in MISSING else h['max']}")
            else:
                grand[kind][0] += h["min"]
                grand[kind][1] += h["max"]
            if eur in MISSING:
                unknown.append(f"`{r['id']}`: EUR cost {eur}")
            else:
                grand[kind][2] += eur
            prereq = "; ".join(md(x) for x in r["prerequisites"]) or "None stated"
            label = f"{n}.{i}" + (" (optional)" if kind == "optional" else "")
            out.write(
                f"| {label} | {link(r)}<br>{anchor(r)} | {prereq} | {hours_text(r)} | {price_text(r)} "
                f"| {cred_label(r)} | {md(step['why'])} |\n"
            )
        out.write("\n")
    out.write("## Totals\n\n")
    out.write("| Path | Study hours (published estimates) | Headline cost (approx. EUR) |\n|---|---|---|\n")
    c, o = grand["core"], grand["optional"]
    out.write(f"| Core steps | {c[0]:,.0f}–{c[1]:,.0f} h | EUR {c[2]:,.0f} |\n")
    out.write(f"| Core + optional | {c[0] + o[0]:,.0f}–{c[1] + o[1]:,.0f} h | EUR {c[2] + o[2]:,.0f} |\n\n")
    out.write("Headline costs exclude VAT, exam retakes, renewals, cloud usage and the extra costs listed on each record.\n\n")
    if unknown:
        out.write("**Not included in totals:**\n\n" + "".join(f"- {u}\n" for u in unknown) + "\n")
    if path.get("notes"):
        out.write("## Notes\n\n" + "".join(f"- {md(x)}\n" for x in path["notes"]) + "\n")
    return out.getvalue()


def csv_text(db) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow([
        "id", "status", "title", "provider", "platform", "official_url", "offering_type", "categories", "level",
        "free_or_paid", "pricing_model", "advertised_price", "amount", "currency", "eur_approx", "study_hours_min",
        "study_hours_max", "format", "credential_type", "credential_issuer", "rating_class", "rating_value",
        "rating_scale", "rating_count", "rating_platform", "suitability", "confidence", "last_verified",
        "completion_status",
    ])
    for r in sorted(db["records"], key=lambda r: r["id"]):
        rt, p, h = r["learner_rating"], r["pricing"], r["delivery"]["study_hours"]
        pub = rt["status"] == "published"
        w.writerow([
            r["id"], r["status"], r["title"], r["provider"], r["platform"], r["official_url"], r["offering_type"],
            ";".join(r["categories"]), r["level"], "free" if is_free(r) else "paid", p["model"], p["advertised"],
            p["amount"], p["currency"], p["eur_approx"], h["min"], h["max"], r["delivery"]["format"],
            r["credential"]["type"], r["credential"]["issuer"], r["rating_class"],
            rt["value"] if pub else rt["status"], rt["scale"] if pub else "", rt["review_count"] if pub else "",
            rt["platform"] if pub else "", r["suitability"]["score"], r["suitability"]["confidence"],
            r["verification"]["last_verified"], r["user"]["completion_status"],
        ])
    return buf.getvalue()


def render(db, path) -> dict[str, str]:
    outputs = {
        "CATALOGUE.md": catalogue_md(db),
        "SHORTLISTS.md": shortlists_md(db),
        "trainings.csv": csv_text(db),
    }
    if path is not None:
        outputs["LEARNING_PATH.md"] = learning_path_md(db, path)
    return outputs


def stale_outputs(db, path) -> list[str]:
    stale = []
    for name, text in render(db, path).items():
        target = CATALOGUE_DIR / name
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            stale.append(name)
    return stale


def main() -> int:
    db = load_json(DB_PATH)
    path = load_json(PATH_PATH) if PATH_PATH.exists() else None
    CATALOGUE_DIR.mkdir(exist_ok=True)
    for name, text in render(db, path).items():
        (CATALOGUE_DIR / name).write_text(text, encoding="utf-8")
        print(f"wrote catalogue/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
